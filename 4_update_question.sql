CREATE DATABASE EMPLOYEE;
USE EMPLOYEE;

CREATE TABLE EMPLOYEES ( 
EMPLOYEE_ID INT PRIMARY KEY AUTO_INCREMENT,
NAME VARCHAR(100),
DEPARTMENT ENUM('IT','HR','FINANCE'),
SALARY INT,
CITY ENUM('KOCHI','CHENNAI','BANGALORE','MUMBAI')
);

