CREATE DATABASE CollegeDB;
USE CollegeDB;
CREATE TABLE Students ( 
ID INT PRIMARY KEY AUTO_INCREMENT ,
NAME VARCHAR(50) ,
AGE INT , 
GENDER ENUM('Male','Female') ,
DEPARTMENT VARCHAR (100) ,
MARKS INT CHECK( MARKS <=100 ),
CITY VARCHAR (100)
);

