UPDATE students 
SET DOB=CASE 
WHEN ID=104 THEN '2004-10-12'
WHEN ID=105 THEN '2003-12-12'
WHEN ID=106 THEN '2004-09-02'
WHEN ID=107 THEN '2002-02-04'
END
WHERE ID IN (104,105,106,107);

ALTER TABLE students ADD COLUMN CITY ENUM('KOCHI','TRIVANDRUM','ATTINGAL') DEFAULT 'ATTINGAL';

UPDATE students 
SET CITY = CASE
WHEN ID % 3 = 0 THEN 'KOCHI'
WHEN ID % 3 = 1 THEN 'TRIVANDRUM'
WHEN ID % 3 = 2 THEN 'ATTINGAL'
END 
WHERE ID BETWEEN 104 AND 137;

